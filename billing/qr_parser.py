import re
import json
from decimal import Decimal, InvalidOperation
from django.db.models import Q
from billing.models import Invoice, InvoiceItem, Customer, Product


def parse_qr_invoice_data(decoded_text):
    """
    Parses decoded QR code content and extracts structured invoice information.
    Handles:
    1. Standard multi-line text format generated by generate_invoice_qr_text:
       Invoice ID: <id>
       Customer: <name>
       Product Count: <count>
       Total Bill: Rs <amount>
       Invoice Date: <date>
    2. JSON-formatted QR content:
       {"invoice_number": "...", "customer": "...", "total": ...}
    3. Standalone invoice numbers/identifiers:
       INV-2026-001 or 123
    4. URL formatted invoice references:
       /invoice/123/pdf/
    
    If the invoice exists in the database, populates complete authoritative
    product line items, tax breakdown, and customer details.
    If not in the database, safely prepares structured fallback information.
    """
    result = {
        'is_valid': False,
        'raw_text': decoded_text or '',
        'invoice_number': None,
        'invoice_date': None,
        'customer': {
            'name': 'Unknown Customer',
            'phone': '',
            'email': '',
            'address': '',
        },
        'items': [],
        'product_count': 0,
        'subtotal': 0.00,
        'tax_details': {
            'gst_rate': 0.0,
            'tax_amount': 0.00,
            'cgst': 0.00,
            'sgst': 0.00,
        },
        'grand_total': 0.00,
        'payment_status': 'Paid',
        'is_database_backed': False,
        'invoice_id': None,
        'error': None,
    }

    if not decoded_text or not isinstance(decoded_text, str) or not decoded_text.strip():
        result['error'] = 'Decoded QR content is empty or invalid.'
        return result

    clean_text = decoded_text.strip()
    extracted_inv_num = None
    extracted_customer = None
    extracted_prod_count = 0
    extracted_total = None
    extracted_date = None
    extracted_items = []

    # Strategy 1: Check for JSON payload
    if (clean_text.startswith('{') and clean_text.endswith('}')) or (clean_text.startswith('[') and clean_text.endswith(']')):
        try:
            json_data = json.loads(clean_text)
            if isinstance(json_data, dict):
                extracted_inv_num = (
                    json_data.get('invoice_number') or
                    json_data.get('invoice_id') or
                    json_data.get('inv_id') or
                    json_data.get('id')
                )
                cust_val = (
                    json_data.get('customer') or
                    json_data.get('customer_name') or
                    json_data.get('client') or
                    json_data.get('billed_to')
                )
                if isinstance(cust_val, dict):
                    extracted_customer = cust_val.get('name') or cust_val.get('customer_name')
                    if cust_val.get('phone'):
                        result['customer']['phone'] = str(cust_val.get('phone'))
                    if cust_val.get('email'):
                        result['customer']['email'] = str(cust_val.get('email'))
                    if cust_val.get('address'):
                        result['customer']['address'] = str(cust_val.get('address'))
                elif isinstance(cust_val, str):
                    extracted_customer = cust_val

                if json_data.get('phone') and not result['customer']['phone']:
                    result['customer']['phone'] = str(json_data.get('phone'))
                if json_data.get('email') and not result['customer']['email']:
                    result['customer']['email'] = str(json_data.get('email'))
                if json_data.get('address') and not result['customer']['address']:
                    result['customer']['address'] = str(json_data.get('address'))

                extracted_total = json_data.get('total') or json_data.get('total_amount') or json_data.get('grand_total')
                extracted_date = json_data.get('date') or json_data.get('invoice_date') or json_data.get('created_at')
                if isinstance(json_data.get('items'), list):
                    extracted_items = json_data.get('items')
                    extracted_prod_count = len(extracted_items)
        except Exception:
            pass

    # Strategy 2: Multi-line Key-Value text matching (Standard project QR format)
    if not extracted_inv_num:
        inv_match = re.search(r'(?:invoice\s*(?:id|number|no|#)?|inv\s*(?:id|no|#)?)\s*[:=-]\s*([^\r\n]+)', clean_text, re.IGNORECASE)
        if inv_match:
            extracted_inv_num = inv_match.group(1).strip()

    if not extracted_customer:
        cust_match = re.search(r'(?:customer\s*(?:name|details)?)\s*[:=-]\s*([^\r\n]+)', clean_text, re.IGNORECASE)
        if cust_match:
            extracted_customer = cust_match.group(1).strip()

    if not extracted_prod_count:
        count_match = re.search(r'(?:product\s*count|item\s*count|items|qty)\s*[:=-]\s*(\d+)', clean_text, re.IGNORECASE)
        if count_match:
            try:
                extracted_prod_count = int(count_match.group(1).strip())
            except ValueError:
                extracted_prod_count = 0

    if extracted_total is None:
        total_match = re.search(r'(?:total\s*(?:bill|amount)?|grand\s*total)\s*[:=-]\s*(?:Rs\.?|INR|₹)?\s*([\d,]+(?:\.\d{1,2})?)', clean_text, re.IGNORECASE)
        if total_match:
            raw_amt = total_match.group(1).replace(',', '').strip()
            try:
                extracted_total = Decimal(raw_amt)
            except (InvalidOperation, ValueError):
                extracted_total = None

    if not extracted_date:
        date_match = re.search(r'(?:invoice\s*date|date)\s*[:=-]\s*([^\r\n]+)', clean_text, re.IGNORECASE)
        if date_match:
            extracted_date = date_match.group(1).strip()

    # Strategy 3: URL or standalone identifier
    if not extracted_inv_num:
        url_match = re.search(r'/invoice/(?:pdf/|qr/)?([a-zA-Z0-9_\-]+)', clean_text)
        if url_match:
            extracted_inv_num = url_match.group(1).strip()
        elif re.match(r'^(?:INV-)?\d+(?:-[A-Za-z0-9]+)?$', clean_text):
            extracted_inv_num = clean_text

    # Database Lookup for the identified invoice
    invoice_obj = None
    if extracted_inv_num:
        extracted_inv_num_str = str(extracted_inv_num).strip()
        # Look up by invoice_number
        invoice_obj = Invoice.objects.filter(
            invoice_number__iexact=extracted_inv_num_str
        ).select_related('customer').prefetch_related('items__product').first()

        # Look up by numeric primary key
        if not invoice_obj and extracted_inv_num_str.isdigit():
            invoice_obj = Invoice.objects.filter(
                id=int(extracted_inv_num_str)
            ).select_related('customer').prefetch_related('items__product').first()

        # Look up by stripped digits (e.g., "INV-1001" -> 1001)
        if not invoice_obj:
            digit_only = re.sub(r'[^\d]', '', extracted_inv_num_str)
            if digit_only and digit_only.isdigit():
                invoice_obj = Invoice.objects.filter(
                    id=int(digit_only)
                ).select_related('customer').prefetch_related('items__product').first()

    # Populate result from Database Record if found
    if invoice_obj:
        result['is_valid'] = True
        result['is_database_backed'] = True
        result['invoice_id'] = invoice_obj.id
        result['invoice_obj'] = invoice_obj
        result['invoice_number'] = invoice_obj.invoice_number or str(invoice_obj.id)
        result['invoice_date'] = invoice_obj.created_at.strftime('%d-%m-%Y') if invoice_obj.created_at else (extracted_date or '')
        result['payment_status'] = dict(Invoice.PAYMENT_STATUS_CHOICES).get(invoice_obj.payment_status, invoice_obj.payment_status.title())

        if invoice_obj.customer:
            result['customer'] = {
                'name': invoice_obj.customer.name or 'Unknown Customer',
                'phone': invoice_obj.customer.phone or '',
                'email': invoice_obj.customer.email or '',
                'address': invoice_obj.customer.address or '',
            }

        calc_subtotal = Decimal('0.00')
        calc_tax = Decimal('0.00')
        items_list = []

        db_items = list(invoice_obj.items.all())
        result['product_count'] = len(db_items)

        for idx, item in enumerate(db_items, start=1):
            qty = item.quantity or 1
            u_price = item.unit_price or Decimal('0.00')
            line_subtotal = (u_price * qty)
            calc_subtotal += line_subtotal

            gst_rate = item.product.gst_rate if (item.product and item.product.gst_rate is not None) else Decimal('0.00')
            item_tax = (line_subtotal * (gst_rate / Decimal('100'))).quantize(Decimal('0.01'))
            calc_tax += item_tax

            items_list.append({
                'sr_no': idx,
                'product_name': item.product.name if item.product else 'Standard Item',
                'category': item.product.category if item.product else 'General',
                'quantity': qty,
                'unit_price': float(u_price),
                'total_price': float(item.total_price if item.total_price is not None else (line_subtotal + item_tax)),
                'gst_rate': float(gst_rate),
                'tax_amount': float(item_tax),
            })

        result['items'] = items_list
        result['subtotal'] = float(calc_subtotal)
        result['tax_details'] = {
            'gst_rate': float(items_list[0]['gst_rate']) if items_list else 0.0,
            'tax_amount': float(calc_tax),
            'cgst': float(calc_tax / Decimal('2')),
            'sgst': float(calc_tax / Decimal('2')),
        }
        result['grand_total'] = float(invoice_obj.total_amount if invoice_obj.total_amount is not None else (calc_subtotal + calc_tax))

    # Fallback: Populate safely from Extracted QR Text when not in database
    else:
        if extracted_inv_num or extracted_total is not None or extracted_customer:
            result['is_valid'] = True

        result['invoice_number'] = str(extracted_inv_num) if extracted_inv_num else 'N/A'
        result['invoice_date'] = str(extracted_date) if extracted_date else 'N/A'
        if extracted_customer:
            result['customer']['name'] = str(extracted_customer)

        total_num = 0.00
        if extracted_total is not None:
            try:
                total_num = float(extracted_total)
            except (ValueError, TypeError):
                total_num = 0.00

        result['grand_total'] = total_num
        result['subtotal'] = total_num
        result['product_count'] = extracted_prod_count or len(extracted_items) or 1

        if extracted_items:
            formatted_items = []
            for idx, itm in enumerate(extracted_items, start=1):
                qty = itm.get('quantity', 1)
                u_price = itm.get('unit_price', 0.0)
                formatted_items.append({
                    'sr_no': idx,
                    'product_name': itm.get('name', f'Item #{idx}'),
                    'category': itm.get('category', 'General'),
                    'quantity': qty,
                    'unit_price': float(u_price),
                    'total_price': float(itm.get('total', float(qty) * float(u_price))),
                    'gst_rate': float(itm.get('gst_rate', 0.0)),
                    'tax_amount': 0.0,
                })
            result['items'] = formatted_items
        else:
            # Construct readable default item representation
            result['items'] = [{
                'sr_no': 1,
                'product_name': f"Verified Merchandise ({result['product_count']} item{'s' if result['product_count'] > 1 else ''})",
                'category': 'General Goods',
                'quantity': result['product_count'],
                'unit_price': float(total_num / result['product_count']) if result['product_count'] > 0 else total_num,
                'total_price': total_num,
                'gst_rate': 0.0,
                'tax_amount': 0.00,
            }]

    return result
